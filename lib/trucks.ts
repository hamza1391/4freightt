export function getTruck(unit: string) {
  return trucks.find((truck) => truck.unit.toLowerCase() === unit.toLowerCase());
}

export function trucksByUnits(units: string[]) {
  return units
    .map((unit) => getTruck(unit))
    .filter((truck): truck is Truck => Boolean(truck));
}
